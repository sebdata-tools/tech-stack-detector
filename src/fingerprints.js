// The fingerprint table: how each technology shows itself in ONE plain HTTP response for a homepage.
// Written by hand from public knowledge of each product (its CDN host names, response headers, cookie names,
// generator tags and documented markers). It is not derived from any other detector's database.
//
// Rule kinds (every regex is case-insensitive; a named group (?<v>...) captures the version):
//   hd(name, re?)  response header `name`; without a regex the header's presence is the signal
//   ck(re)         name of a cookie set by the response
//   mt(name, re)   <meta name|property=name content=...>
//   u(re)          URL in <script src>, <link href> or <iframe src>
//   ht(re)         anywhere in the HTML source
//   js(re)         inside an inline <script>
// A rule is 'high' confidence unless M ('medium') is passed last. Precision beats recall here:
// a pattern must be a host name or a marker that only this technology produces.

export const M = 'medium';
const rule = (type, key, re, confidence) => ({ type, key, re, confidence: confidence ?? 'high' });
const hd = (key, re, c) => (typeof re === 'string' ? rule('header', key, undefined, re) : rule('header', key, re, c));
const ck = (re, c) => rule('cookie', undefined, re, c);
const mt = (key, re, c) => rule('meta', key, re, c);
const u = (re, c) => rule('url', undefined, re, c);
const ht = (re, c) => rule('html', undefined, re, c);
const js = (re, c) => rule('inline', undefined, re, c);
const gen = (re, c) => mt('generator', re, c);
/** Matches only when every given rule matches (for signals that are too weak alone). */
const all = (rules, confidence) => ({ type: 'all', rules, confidence: confidence ?? 'high' });
const T = (name, category, rules, implies = []) => ({ name, category, rules, implies });

